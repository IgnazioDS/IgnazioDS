GLYPH_H = 7
SPACING = 1


def glyph(ch):
    key = "*" if ch == "·" else ch.upper()
    if key not in GLYPHS:
        raise ValueError(f"no glyph for {ch!r}")
    return GLYPHS[key]


def measure(text):
    widths = [len(glyph(ch)[0]) for ch in text]
    return sum(widths) + SPACING * max(0, len(widths) - 1)


def render(text, fill, outline=raster.rgb("#07050a"), shadow=True):
    """fill: one color or a top-to-bottom tuple ramp (one entry per glyph row)."""
    ramp = fill if isinstance(fill, tuple) else (fill,) * GLYPH_H
    if len(ramp) != GLYPH_H:
        raise ValueError(f"fill ramp needs {GLYPH_H} colors, got {len(ramp)}")
    pad = 1
    width = measure(text) + pad * 2 + (1 if shadow else 0)
    height = GLYPH_H + pad * 2 + (1 if shadow else 0)
    ink = raster.Canvas(width, height)
    x = pad
    for ch in text:
        rows = glyph(ch)
        for gy, row in enumerate(rows):
            for gx, bit in enumerate(row):
                if bit == "#":
                    ink.put(x + gx, pad + gy, ramp[gy])
        x += len(rows[0]) + SPACING
    return _outlined(ink.freeze(), outline, shadow)


def _outlined(image, outline, shadow):
    canvas = raster.Canvas(image.width, image.height)
    offsets = [(dx, dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1) if dx or dy]
    if shadow:
        offsets.append((1, 2))
        offsets.append((2, 1))
    for y in range(image.height):
        for x in range(image.width):
            if raster.alpha_of(image.at(x, y)):
                for dx, dy in offsets:
                    canvas.put(x + dx, y + dy, outline)
    canvas.blit(image, 0, 0)
    return canvas.freeze()


